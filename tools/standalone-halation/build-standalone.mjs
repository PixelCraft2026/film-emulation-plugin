// tools/standalone-halation/build-standalone.mjs
// 把 halation-cli.js 打包为自包含单文件 halation-cli.standalone.js：
// core 算法 + jpeg-js + pngjs 全部打进 bundle，仅保留 node 内置模块外部依赖。
// 用户只需复制 standalone 文件 + run.bat 到图片文件夹即可双击运行。
import esbuild from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));

await esbuild.build({
  entryPoints: [path.join(dir, 'halation-cli.js')],
  bundle: true,
  // .cjs 扩展名：Node 对 .cjs 一律按 CommonJS 解析，与所在目录是否有
  // package.json（type:module）无关——用户把文件复制到任何文件夹都正常。
  outfile: path.join(dir, 'halation-cli.standalone.cjs'),
  platform: 'node',
  format: 'cjs',
  target: 'node18',
  logLevel: 'info',
  banner: { js: '// Film Halation standalone bundle - generated by build-standalone.mjs. Do not edit.' },
});

console.log('standalone bundle written: tools/standalone-halation/halation-cli.standalone.cjs');
